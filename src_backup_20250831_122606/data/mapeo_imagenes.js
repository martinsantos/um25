// Función de búsqueda mejorada
export function buscarImagenPorDatos(cliente, area, titulo, id) {
    console.log('[MAPEO] Buscando imagen para:', { cliente, area, titulo, id });
    
    // Normalizar datos para comparación
    const normalizarTexto = (texto) => {
        if (!texto) return '';
        return texto
            .toLowerCase()
            .normalize("NFD").replace(/[\u0300-\u036f]/g, "")
            .replace(/[^\w\s]/g, ' ')
            .trim()
            .replace(/\s+/g, ' ');
    };
    
    const clienteNorm = normalizarTexto(cliente);
    const areaNorm = normalizarTexto(area);
    const tituloNorm = normalizarTexto(titulo);
    
    // Buscar coincidencia exacta por ID
    if (id) {
        const porId = mapeoImagenes.find(item => 
            item.numero && item.numero.toString() === id.toString()
        );
        if (porId) {
            console.log('[MAPEO] ✅ Encontrada por ID:', porId.nombre_archivo_generado);
            return porId.nombre_archivo_generado;
        }
    }
    
    // Buscar por cliente y área
    if (cliente && area) {
        const porClienteArea = mapeoImagenes.find(item => {
            const itemClienteNorm = normalizarTexto(item.cliente);
            const itemAreaNorm = normalizarTexto(item.area);
            
            return itemClienteNorm.includes(clienteNorm) && 
                   (itemAreaNorm.includes(areaNorm) || areaNorm.includes(itemAreaNorm));
        });
        
        if (porClienteArea) {
            console.log('[MAPEO] ✅ Encontrada por cliente+área:', porClienteArea.nombre_archivo_generado);
            return porClienteArea.nombre_archivo_generado;
        }
    }
    
    // Buscar solo por cliente
    if (cliente) {
        const porCliente = mapeoImagenes.find(item => {
            const itemClienteNorm = normalizarTexto(item.cliente);
            return itemClienteNorm.includes(clienteNorm) || clienteNorm.includes(itemClienteNorm);
        });
        
        if (porCliente) {
            console.log('[MAPEO] ✅ Encontrada por cliente:', porCliente.nombre_archivo_generado);
            return porCliente.nombre_archivo_generado;
        }
    }
    
    // Buscar por título
    if (titulo) {
        const porTitulo = mapeoImagenes.find(item => {
            if (!item.titulo_original) return false;
            const itemTituloNorm = normalizarTexto(item.titulo_original);
            return itemTituloNorm.includes(tituloNorm) || tituloNorm.includes(itemTituloNorm);
        });
        
        if (porTitulo) {
            console.log('[MAPEO] ✅ Encontrada por título:', porTitulo.nombre_archivo_generado);
            return porTitulo.nombre_archivo_generado;
        }
    }
    
    console.log('[MAPEO] ❌ No se encontró imagen específica');
    return null;
}

